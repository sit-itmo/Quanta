#!/usr/bin/env python3
"""Regenerate checked-in C documentation; not required for ordinary builds."""
from pathlib import Path
import argparse, json, re, sys
ROOT = Path(__file__).resolve().parents[1]

def render():
    by_key={}
    for subdir,platform in [('', 'QUANTA_OS_LINUX'),('windows','QUANTA_OS_WINDOWS')]:
        for definition in sorted((ROOT/'metrics'/subdir).glob('*.def')):
            if definition.stem=='selected': continue
            flag=platform
            if definition.stem=='mcu':
                flag='QUANTA_PLATFORM_FREERTOS'
            elif definition.stem=='smbios_mem':
                flag='(QUANTA_OS_LINUX || QUANTA_OS_WINDOWS) && QUANTA_WITH_DMI && QUANTA_ARCH_X86'
            elif definition.stem=='os' and not subdir:
                flag='(QUANTA_OS_LINUX || QUANTA_PLATFORM_FREERTOS)'
            if definition.stem not in ('os','mcu','smbios_mem'): flag+=' && QUANTA_WITH_'+definition.stem.upper()
            if definition.stem=='cpuid': flag+=' && QUANTA_ARCH_X86'
            keys=re.findall(r'\.key\s*=\s*"([^"]+)"',definition.read_text(encoding='utf-8'))
            if len(set(keys))!=len(keys): raise RuntimeError('Duplicate keys in '+str(definition))
            for key in keys:
                item=by_key.setdefault(key,[])
                if any(previous.startswith(platform) for previous in item):
                    raise RuntimeError('Duplicate '+platform+' key: '+key)
                item.append(flag)
    entries=[(key,' || '.join('('+flag+')' for flag in flags),
              (ROOT/'docs/metrics'/(key+'.md')).read_text(encoding='utf-8'))
             for key,flags in sorted(by_key.items())]
    if not entries: raise RuntimeError('No registry descriptors found')
    out=['/* SPDX-License-Identifier: MIT -- generated by tools/embed_docs.py */',
         '#include "collector_internal.h"', '#if QUANTA_EMBED_DOCS']
    for i,(key,flag,text) in enumerate(entries):
        out+=['#if '+flag, 'static const char doc_'+str(i)+'[] =']
        out += ['    '+json.dumps(line,ensure_ascii=False) for line in text.splitlines(keepends=True)]
        out+=[';', '#endif']
    out+=['typedef struct doc_entry { const char *key; const char *text; } doc_entry;',
          'static const doc_entry docs[] = {']
    for i,(key,flag,text) in enumerate(entries):
        out+=['#if '+flag,'    {"'+key+'", doc_'+str(i)+'},','#endif']
    out+=['    {NULL, NULL}', '};', '#endif',
          'const char *quanta_metric_documentation(const char *key) {',
          '#if QUANTA_EMBED_DOCS', '    size_t i;',
          '    for (i=0; docs[i].key; i++) if (!strcmp(key, docs[i].key)) return docs[i].text;',
          '#else', '    (void)key;', '#endif', '    return NULL;', '}']
    return '\n'.join(out)+'\n'

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    content=render();target=ROOT/'sensors/metric_docs.c'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8')!=content:
            print('Embedded docs are stale; run python3 tools/embed_docs.py',file=sys.stderr);return 1
        print('Embedded docs match the metric registry and Markdown files');return 0
    target.write_text(content,encoding='utf-8');print('Updated',target);return 0
if __name__=='__main__':
    try:sys.exit(main())
    except (OSError,ValueError,RuntimeError) as exc:print('embed_docs:',exc,file=sys.stderr);sys.exit(1)
